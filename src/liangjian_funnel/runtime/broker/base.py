"""Common local-paper / future broker protocol. No SDK imports or credentials."""
from collections.abc import Mapping
from typing import Any, Protocol


class BrokerAdapter(Protocol):
    def get_account(self) -> Mapping[str, Any]: ...
    def get_positions(self) -> tuple[Mapping[str, Any], ...]: ...
    def place_order(self, symbol: str, side: str, qty: int, *, order_type: str,
                    limit_price: str | None, client_order_id: str, plan_id: str,
                    signal_id: str, **evidence: Any) -> str: ...
    def cancel_order(self, order_id: str) -> Mapping[str, Any]: ...
    def get_orders(self, trade_date: str) -> tuple[Mapping[str, Any], ...]: ...
    def get_fills(self, trade_date: str) -> tuple[Mapping[str, Any], ...]: ...
    def on_bar(self, minute_bar: Any) -> tuple[Mapping[str, Any], ...]: ...
    def reconcile(self) -> Mapping[str, Any]: ...
